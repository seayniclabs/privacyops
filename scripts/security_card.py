#!/usr/bin/env python3
"""Print the README security card from the live server, so its numbers are measured, not typed.

Token footprint = characters of everything an app loads at startup (instructions, tool
definitions, prompt list) divided by 4, the usual rule of thumb for English and JSON.
Usage: python scripts/security_card.py   (paste the output into the README, or use --check in CI)
"""

from __future__ import annotations

import asyncio
import inspect
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from privacyops_mcp.config import Config  # noqa: E402
from privacyops_mcp.server import build_server  # noqa: E402

# Tools that need the person's approval before they change anything.
APPROVAL_GATED = ("disputes_delete",)

NETWORK = "None. PrivacyOps makes no outbound network calls and has no telemetry. Only `--transport http` opens a listener, on 127.0.0.1 unless you change `--host`."
FILES = ("Reads its config file (`~/.config/privacyops/config.toml`, if present). Reads and writes its records file and "
         "letter text files in its data folder (`~/.local/share/privacyops`), owner-only. Appends one line per approval "
         "decision to `~/.local/state/privacyops/approvals.jsonl` (ids only).")
SECRETS = ("PrivacyOps stores no passwords or API keys and has no tool that takes one. It never asks for a Social "
           "Security number.")



def _clean(d: dict) -> dict:
    """Same text on every Python: 3.13 strips docstring indentation, earlier versions keep it."""
    if d.get("description"):
        d["description"] = inspect.cleandoc(d["description"])
    return d

def card() -> str:
    srv = build_server(Config(env={}, file_data={}))
    tools = asyncio.run(srv.list_tools())
    prompts = asyncio.run(srv.list_prompts())
    names = {t.name for t in tools}
    missing = [n for n in APPROVAL_GATED if n not in names]
    if missing:
        raise SystemExit(f"security_card: approval-gated tools not found: {missing}")
    startup = (srv.instructions or "") + json.dumps([_clean(t.model_dump(exclude_none=True, mode="json")) for t in tools]) \
        + json.dumps([_clean(p.model_dump(exclude_none=True, mode="json")) for p in prompts])
    read_only = [t.name for t in tools if t.annotations and t.annotations.readOnlyHint]
    writes = [t.name for t in tools if t.name not in read_only and t.name not in APPROVAL_GATED]
    gated = [n for n in APPROVAL_GATED]
    return "\n".join([
        "<!-- security-card:start (generated by scripts/security_card.py) -->",
        "| Security card | |",
        "|---|---|",
        f"| Network | {NETWORK} |",
        f"| Files | {FILES} |",
        f"| Secrets | {SECRETS} |",
        f"| Read-only tools | {len(read_only)}: {', '.join(f'`{n}`' for n in read_only)} |",
        f"| Writes on this computer | {', '.join(f'`{n}`' for n in writes)}: local files only, no approval needed. Each dispute change is recorded in its history. |",
        f"| Needs your approval | {', '.join(f'`{n}`' for n in gated)}: you approve each delete in your app, or pre-approve in settings. The AI cannot approve for you. |",
        f"| Startup cost | about {round(len(startup) / 4, -2):,.0f} tokens ({len(tools)} tools, {len(prompts)} skill prompts) |",
        "| Changes | Tool descriptions are locked by hash (`tool-manifest.lock.json`); CI fails if they change silently. |",
        "<!-- security-card:end -->",
    ])


def main() -> int:
    text = card()
    if "--check" in sys.argv:
        readme = (ROOT / "README.md").read_text()
        m = re.search(r"<!-- security-card:start.*?<!-- security-card:end -->", readme, re.S)
        ok = bool(m) and m.group(0) == text
        print("security card is current" if ok else "README security card is stale: run scripts/security_card.py")
        return 0 if ok else 1
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
