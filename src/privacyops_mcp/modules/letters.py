"""Letters: dispute letters from fixed templates, written as text files in the data folder.

Nothing is generated by a model. Names and addresses of the person are placeholders, filled in by
hand. No identifying number or Social Security field exists anywhere in this module.
"""

from __future__ import annotations

import uuid
from typing import Literal

from mcp.server.fastmcp import FastMCP
from mcp.types import ToolAnnotations
from pydantic import BaseModel, Field

from .. import __version__
from ..common import DISCLAIMER, clean, now_iso, today
from ..config import Config
from ..errors import PrivacyOpsError
from ..store import Store, atomic_write
from ..templates import (
    ADDRESS_PLACEHOLDER, AGENCIES, CHECKED, ENCLOSURES, IDENTIFIERS, SIGNATURE, TEMPLATES, YOUR_ADDRESS,
    YOUR_NAME, agency,
)
from . import Module

TemplateId = Literal["cra_dispute", "furnisher_dispute"]
READ_ONLY = ToolAnnotations(readOnlyHint=True, openWorldHint=False)
WRITES_LOCAL = ToolAnnotations(readOnlyHint=False, destructiveHint=False, idempotentHint=False, openWorldHint=False)
LIMITS = {"item_description": 2000, "reason": 2000, "recipient_name": 120, "recipient_address": 500}


class TemplateInfo(BaseModel):
    id: str
    title: str
    recipient: str
    cites: list[str]
    sources: list[str]
    version: str


class AgencyInfo(BaseModel):
    key: str
    name: str
    dispute_url: str | None = None
    mail_address: list[str] | None = None
    source_url: str | None = None
    source_checked: str | None = None
    note: str


class TemplateList(BaseModel):
    disclaimer: str
    templates: list[TemplateInfo]
    agencies: list[AgencyInfo] = Field(description="Only contact details checked on the official site are shown.")


class Recipient(BaseModel):
    name: str | None = None
    address: list[str] | None = None
    address_source: str


class LetterResult(BaseModel):
    letter_id: str
    template: str
    path: str
    recipient: Recipient
    dispute_id: str | None = None
    text: str
    disclaimer: str = DISCLAIMER


class LettersModule(Module):
    def __init__(self) -> None:
        super().__init__(
            name="letters",
            summary="Dispute letters from fixed, reviewed-by-no-one templates, saved as text files on this "
                    "machine. Not legal advice.",
            settings=[],
            tools={
                "letters_templates": "The available templates, the agencies with checked contact details, and the disclaimer.",
                "letters_generate": "Write a dispute letter to a file. Placeholders are left for you to fill in by hand.",
            },
        )

    def register(self, mcp: FastMCP, config: Config, store: Store) -> None:
        @mcp.tool(annotations=READ_ONLY)
        def letters_templates() -> TemplateList:
            """The letter templates, the agencies with checked contact details, and the disclaimer. Read this before generating a letter."""
            return TemplateList(
                disclaimer=DISCLAIMER,
                templates=[TemplateInfo(id=t.id, title=t.title, recipient=t.recipient, cites=list(t.cites),
                                        sources=list(t.sources), version=t.version)
                           for t in TEMPLATES.values()],
                agencies=[AgencyInfo(key=a.key, name=a.name, dispute_url=a.dispute_url,
                                     mail_address=list(a.mail_address) if a.mail_address else None,
                                     source_url=a.source_url, source_checked=a.source_checked, note=a.note)
                          for a in AGENCIES],
            )

        @mcp.tool(annotations=WRITES_LOCAL)
        def letters_generate(template: TemplateId, item_description: str, reason: str | None = None,
                             agency_key: str | None = None, recipient_name: str | None = None,
                             recipient_address: str | None = None, dispute_id: str | None = None) -> LetterResult:
            """Write a dispute letter from a fixed template to a text file. Your name, address and signature are
            placeholders to fill in by hand. For a credit agency pass agency_key (equifax, experian, transunion) or
            recipient_name. Pass dispute_id to attach the letter to a dispute record. Not legal advice."""
            tpl = TEMPLATES[template]
            item = clean(item_description, "letters", "item_description", LIMITS["item_description"], required=True)
            why = clean(reason, "letters", "reason", LIMITS["reason"])
            if dispute_id is not None and dispute_id not in store.read()["disputes"]:
                raise PrivacyOpsError("disputes", "not_found", f"no dispute with id {dispute_id!r}.",
                                      "call disputes_list to find the id, or omit dispute_id.")

            name: str | None
            lines: list[str] | None
            source: str
            if agency_key:
                a = agency(agency_key)
                if a is None:
                    raise PrivacyOpsError("letters", "bad_input", f"unknown agency_key {agency_key!r}.",
                                          "use equifax, experian or transunion, or pass recipient_name instead.")
                name = a.name
                lines = list(a.mail_address) if a.mail_address else None
                source = (f"from {a.source_url}, checked {a.source_checked}" if lines
                          else "not published on the official site: fill in by hand")
            else:
                name = clean(recipient_name, "letters", "recipient_name", LIMITS["recipient_name"],
                             required=True)
                addr = clean(recipient_address, "letters", "recipient_address", LIMITS["recipient_address"])
                lines = addr.split("\n") if addr else None
                source = "supplied by you" if lines else "not provided: fill in by hand"

            if lines:
                block = "\n".join(lines)
            else:
                block = f"{name}\n{ADDRESS_PLACEHOLDER}" if name else ADDRESS_PLACEHOLDER

            date = today()
            body = tpl.body.format(
                your_name=YOUR_NAME, your_address=YOUR_ADDRESS, date=date, recipient_block=block,
                item=item, reason=why or "(describe why the item is wrong)", enclosures=ENCLOSURES,
                signature=SIGNATURE, identifiers=IDENTIFIERS,
            )
            footer = (
                "\n---\n"
                f"{DISCLAIMER}\n"
                f"Template: {tpl.id} (version {tpl.version}). Checked against: "
                f"{'; '.join(tpl.sources)} (checked {CHECKED}). "
                f"Generated by PrivacyOps {__version__} on {date}."
            )
            text = body + footer

            letter_id = f"{date}-{tpl.id}-{uuid.uuid4().hex[:8]}"
            filename = f"{letter_id}.md"
            path = store.letters_dir / filename
            store.ensure_dirs()
            try:
                atomic_write(path, text)
            except OSError as e:
                raise PrivacyOpsError("letters", "write_failed", f"could not save the letter ({e.strerror}).",
                                      "check that PRIVACYOPS_DATA_DIR is writable.")

            if dispute_id is not None:
                def attach(data: dict) -> None:
                    rec = data["disputes"].get(dispute_id)
                    if rec is None:
                        raise PrivacyOpsError("disputes", "not_found", f"no dispute with id {dispute_id!r}.",
                                              "call disputes_list to find the id.")
                    rec.setdefault("letter_files", []).append(filename)
                    rec["history"].append({"at": now_iso(), "action": "letter", "note": filename})
                    rec["updated_at"] = now_iso()
                store.update(attach)

            return LetterResult(
                letter_id=letter_id, template=tpl.id, path=str(path),
                recipient=Recipient(name=name, address=lines, address_source=source),
                dispute_id=dispute_id, text=text,
            )
