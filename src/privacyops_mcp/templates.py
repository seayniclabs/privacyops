"""Fixed letter templates and the consumer reporting agency reference data.

Nothing here is generated by a model. Each template is fixed text with placeholders the
person fills in by hand. Every statute citation was checked against the official text
(Cornell LII, law.cornell.edu) on 2026-10-27. Contact details appear only when they were
checked on the agency's own official site on that date; otherwise the field is left blank.
"""

from __future__ import annotations

from dataclasses import dataclass

CHECKED = "2026-10-27"

# ---- Reference data: consumer reporting agencies --------------------------------

@dataclass(frozen=True)
class Agency:
    key: str
    name: str
    dispute_url: str | None
    mail_address: tuple[str, ...] | None  # full mailing block, first line is the company
    source_url: str | None
    source_checked: str | None
    note: str


# Equifax: the official page links online disputes and publishes no mailing address.
# Experian: the official page publishes the mail address below.
# TransUnion: the official page returned HTTP 403 when checked, so nothing is recorded.
AGENCIES: tuple[Agency, ...] = (
    Agency(
        key="equifax",
        name="Equifax",
        dispute_url="https://www.equifax.com/personal/credit-report-services/credit-dispute/",
        mail_address=None,
        source_url="https://www.equifax.com/personal/credit-report-services/credit-dispute/",
        source_checked=CHECKED,
        note="Online disputes are linked from that page. No mailing address is published there; "
             "fill one in from equifax.com before mailing a letter.",
    ),
    Agency(
        key="experian",
        name="Experian",
        dispute_url="https://www.experian.com/disputes/main.html",
        mail_address=("Experian", "Dispute by Mail", "P.O. Box 4500", "Allen, TX 75013"),
        source_url="https://www.experian.com/disputes/main.html",
        source_checked=CHECKED,
        note="Online disputes need a sign-in on Experian's site. Send copies of documents, not originals.",
    ),
    Agency(
        key="transunion",
        name="TransUnion",
        dispute_url=None,
        mail_address=None,
        source_url=None,
        source_checked=None,
        note="Not verified: the official TransUnion page returned HTTP 403 when checked on "
             f"{CHECKED}. Fill in the dispute link and mailing address from transunion.com.",
    ),
)


def agency(key: str) -> Agency | None:
    for a in AGENCIES:
        if a.key == key.lower():
            return a
    return None


